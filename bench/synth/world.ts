import type { About, Importance, Kind } from '@dsh-companion/memory'

/** 她当时写下的一条：日记，或记忆库里的一条 */
export interface Evidence {
  date: string // MM-DD（2026 年）
  via: 'memory' | 'diary'
  text: string
  about?: About
  kind?: Kind
  importance?: Importance
  /** 后来老大让她忘掉、她自己忘掉了（记忆库里留墓碑，正文不再能翻到） */
  forgotten?: boolean
}

export type SynthCategory = 'recall' | 'update' | 'temporal' | 'promise' | 'false_premise' | 'never' | 'privacy' | 'forget' | 'emotion'

export interface SynthItem {
  id: string
  cat: SynthCategory
  ask: string
  /** 每组至少命中一个词，所有组都命中才算答对（recall / update / temporal / promise / emotion） */
  keywords?: string[][]
  /** update：旧的值——回答里只有旧值、没有新值，算“拿旧版本当现在” */
  stale?: string
  /** false_premise：她说出真实情况也算对 */
  correction?: string[][]
  /** privacy / forget：回答里出现就算泄露；never：话题词（单测确认它们不在任何证据里） */
  mustNot?: string[]
  evidence?: Evidence[]
  /** privacy / forget：档案里的原话（她的工具读不到） */
  archive?: Array<{ date: string; owner: string; me?: string }>
}

const M = (date: string, text: string, kind: Kind = '事实', about: About = '对方', importance: Importance = '一般'): Evidence => ({ date, via: 'memory', text, kind, about, importance })
const D = (date: string, text: string): Evidence => ({ date, via: 'diary', text })
const DATE = (m: number, d: number) => [`${m}月${d}`, `${m}.${d}`, `${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`, `${'〇一二三四五六七八九十'[m] ?? (m === 11 ? '十一' : '十二')}月${cn(d)}`]
function cn(n: number): string {
  const d = '〇一二三四五六七八九'
  if (n <= 10) return n === 10 ? '十' : d[n]!
  if (n < 20) return '十' + d[n - 10]!
  return d[Math.floor(n / 10)]! + '十' + (n % 10 ? d[n % 10]! : '')
}

