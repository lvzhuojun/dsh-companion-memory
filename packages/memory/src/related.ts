const INDEX = new Map<string, string[]>()
for (const g of GROUPS) for (const w of g) INDEX.set(w, [...new Set([...(INDEX.get(w) ?? []), ...g.filter((x) => x !== w)])])

/** 查询里每个词的相关说法（不含原词、去重）；没有就是空数组 */
export function relatedTerms(query: string): string[] {
  const words = query.toLowerCase().split(/[\s，,、。.；;！!？?]+/).filter(Boolean)
  const own = new Set(words)
  const out = new Set<string>()
  for (const w of words) for (const r of INDEX.get(w) ?? []) if (!own.has(r)) out.add(r)
  return [...out]
}
