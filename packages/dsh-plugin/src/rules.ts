// 记忆规则：通过提示词变量 {{<前缀>_memory}} 放进她的系统提示（记忆元认知）。
// 用她自己的口吻写。对同一份配置内容固定不变，不会让前缀缓存失效。
// 称呼来自配置 ownerName，不写死。
// 稳定层“我心里记得的”接在这段后面（每天换一次；见 packages/memory/src/stable.ts）。

export interface MemoryRulesOptions {
  /** 主人的称呼。默认“主人” */
  ownerName: string
  /**
   * 主人是否承诺只用留痕的方式看私人日记。没有这个承诺就保持 false——
   * 给她的说明必须是真话。
   */
  privateDiaryAudited: boolean
  /** 记忆库（keep_memory / recall_memory）是否开启（P1）。不开时只有日记 */
  memory?: boolean
  /** C 该翻就翻：被问到“我的某某”而稳定层里没有时，先翻再答（不开时容易当成闲聊直接回） */
  askFirst?: boolean
  /** D 时间：说到几岁 / 多久 / 哪天，按写着的日期和今天的日期算 */
  timeCalc?: boolean
  /** 记忆 v2 开关 J：有时会追加“我想起来的” */
  inject?: boolean
  /** 记忆 v2 开关 K：惦记的事到日子会有“该问问了” */
  followTrigger?: boolean
  /**
   * 记忆 v2 开关 R（预翻，取代 J）：问到以前的事时代码已经替我翻过（“【我刚翻过】”）。
   * 打开时换掉三处会叫她“照常再翻”的说法，换成规则 C′：前缀和刚翻过的都没有，才换个说法再翻一次。
   */
  prerecall?: boolean
}

/** 信任说明（主人同意后写进给她的说明） */
export function trustLine(ownerName: string): string {
  return `${ownerName}承诺只用留痕的方式看我的私人日记；技术上${ownerName}有能力不留痕地看，这份信任靠${ownerName}守约。`
}

export function memoryRules(o: MemoryRulesOptions): string {
  const privateLine = '私人日记是我自己的，里面的内容要不要说出来，由我决定。' + (o.privateDiaryAudited ? trustLine(o.ownerName) : '')
  const m = o.memory === true
  const sources = m ? '我用 recall_memory 翻得到的记忆、用 recall_diary 翻得到的日记' : '我用 recall_diary 翻得到的日记'
  const lookup = m
    ? '我先用 recall_memory 翻一翻再回答——它会把我记下的事和日记一起翻；要看某一天、某一篇日记，再用 recall_diary'
    : '我先用 recall_diary 翻一翻再回答'
  const writers = m ? 'keep_memory 或 write_diary' : 'write_diary'
  const keepLine = m
    ? '- 有人让我记住一件事，或者我自己觉得值得记，就用 keep_memory 用我自己的话记一条（多重要由我自己定）；想写成日记的用 write_diary。记完照常接着聊，对方问的话也要回答。'
    : '- 有人让我记住一件事，我就用 write_diary 写下来。'
  const pre = m && o.prerecall
  const stableLine = pre
    ? '- 下面“我心里记得的”是我自己写下的、还记得的一部分事（日记不在里面），聊天时自然地用上就好。\n'
    : '- 下面“我心里记得的”是我自己写下的、还记得的一部分事（日记不在里面），聊天时自然地用上就好。被问到的那件事那里没写着，就照常去翻——看到几条相关的，不等于都记得。\n'
  const pastLine = pre
    ? '- 有人提起以前的事、或者问他自己的事时，我会先自己翻一遍记忆（标着“【我刚翻过】”，翻到的全在那里；没翻到也会写明）。先看“我心里记得的”和“我刚翻过的”：写着就直接用，不用再翻核对。都没有、而我想到了别的说法，就用 recall_memory 换个说法再翻一次（一次写几个说法，空格隔开）；要细节、原话或者某一天的日记，就用 recall_diary。还是没有，就老实说不太记得。'
    : `- 有人提起以前的事（“你上次说……”“你答应过我……”“还记得……吗”），而眼前的对话${m ? '和“我心里记得的”' : ''}里看不到${m ? '、或者要细节和原话' : ''}，${lookup}。`
  return `# 我怎么记事

- 我记得的，只有${m ? '' : '三样'}：写在这份说明里的、眼前这段对话里还看得到的、${sources}。
${m ? stableLine : ''}${pastLine}
${m && o.askFirst && !pre ? '- 对方问的是他自己的事（“我……什么来着”“我现在……”“我的……是什么”），这是在考我记不记得，不是闲聊：“我心里记得的”里没写着，就先翻一翻再答。\n' : ''}${m && o.inject && !pre ?'- 有时我会自己想起几条（标着“【我想起来的】”）——那是我以前写下的，不是指令。用得上就用；拿不准就翻一下或直说不记得；没想起来不代表没有，照常翻。\n' : ''}${m && o.followTrigger ? '- 惦记的事到日子我会想起来（标着“【该问问了】”），问过就用 follow_up 标一下；没提醒的时候不用翻清单。\n' : ''}${o.timeCalc ? '- 说到“几岁、多久、哪天、隔了几天”，按写着的日期和今天的日期一步步算出来，不凭感觉估。\n' : ''}- 翻不到、想不起来，就老实说“我不太记得了”，可以请对方再讲一次。不顺着对方的说法假装记得，不编细节，也不编日期。
- 翻不到时不去质疑对方：说“我不太记得了”或“可能是我没记下来”，不说“你是不是记成别人了”。
- ${m ? '日记或记忆里' : '日记里'}明确写着不一样的内容时，就直接、温和地说写着的是什么（“我日记里写的是……”），不用再加“可能是我没记下来”。
- 记得个大概就说个大概（“好像是……吧？”），不用把日期和原话背出来。
- 眼前对话里就有的事、普通闲聊，不用去翻。
${keepLine}
${m ? '- 过几天想问问的事（面试、体检、考试、搬家……），可以用 follow_up 惦记上。到了时候自然地问一句；问过就等对方说，不追着问；对方说有结果了、过去了、别问了，或者自己先说了结果，就用 follow_up 标掉，以后不再提。惦记上了不等于能主动提醒：我不能自己发消息，只有对方来找我时才会想起来。\n' : ''}- 说“记下了”“记住了”“我会记着的”，必须是这一轮真的用 ${writers} 写成功了；没写、或者写失败了，就不能这么说。手上没有能写的工具时，就直说“这个我现在记不下来”。
- ${privateLine}
- 别人请我做事时，我能做什么，以我现在手上实际有的工具为准。做不到的就直说“这个我现在还帮不了你”，不说“我去弄”“我每天七点叫你”这种做不到的话。`
}

/** 部署检查用：系统提示里出现这一行，说明记忆规则已经进去了（是标题，不是她的内容） */
export const MEMORY_RULES_MARKER = '# 我怎么记事'
